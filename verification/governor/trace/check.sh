#!/usr/bin/env bash
# Trace validation of the attention governor: record random runs of the real src/core/governor.ts
# (record.ts) and check with TLC that each is a behavior of verification/governor/Governor.tla
# (GovernorTrace.tla). Then show the check can fail: every mutant (a broken copy of governor.ts,
# or a broken recorder) must have at least one trace rejected.
#
#   bash verification/governor/trace/check.sh                  # 100 traces + 6 mutants, about 45 s on 4 cores
#   bash verification/governor/trace/check.sh --count 200 --seed 1000
#   bash verification/governor/trace/check.sh --no-mutants
#   bash verification/governor/trace/check.sh --replay FILE.ndjson ...   # validate given trace files
#
# Lines: PASS / FAIL per check, then "governor-trace: PASS" or "governor-trace: FAIL". A rejected
# trace prints its first unmatched line, the call and what differs between model and code. Traces,
# TLC output and verdict files stay in verification/out/governor-trace/. Exit 1 on any FAIL.
set -u
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$DIR/../../lib.sh"
ROOT="$(cd "$VERIFY_DIR/.." && pwd)"
command -v java >/dev/null || { echo "FAIL java not found (Java 11 or later is needed)"; exit 2; }
command -v node >/dev/null || { echo "FAIL node not found (Node 22 is needed to run record.ts)"; exit 2; }
JAR=$(find_jar) || exit 2
OUT="$VERIFY_DIR/out/governor-trace"
count=100; seed=1; mcount=40; mutants=1; replay=()
while [ $# -gt 0 ]; do
	case $1 in
		--count) count=$2; shift ;;
		--seed) seed=$2; shift ;;
		--mutant-count) mcount=$2; shift ;;
		--no-mutants) mutants=0 ;;
		--replay) shift; replay=("$@"); break ;;
		*) echo "unknown option $1"; exit 2 ;;
	esac
	shift
done
failed=0
line() { printf '%-8s %-34s %s\n' "$1" "$2" "$3"; }


# validate NAME FILE... : one TLC run over a batch of traces. Sets $acc, $rej (counts), $first
# (the report of the first rejected trace) and $tlc ("ok", or what went wrong).
validate() {
	local name=$1; shift
	local work="$OUT/$name/tlc"
	mkdir -p "$work/res"
	rm -f -- "${work:?}"/res/*.json
	local files="" f
	for f in "$@"; do files="${files:+$files, }\"$(realpath "$f")\""; done
	printf -- '---- MODULE GovernorTraceBatch ----\n\\* Generated by check.sh: the traces of one batch.\nEXTENDS GovernorTrace\nBatchFiles == <<%s>>\nBatchResultDir == "%s"\n====\n' \
		"$files" "$work/res" >"$work/GovernorTraceBatch.tla"
	cp "$DIR/GovernorTrace.cfg" "$work/GovernorTraceBatch.cfg"
	local meta; meta=$(mktemp -d "${TMPDIR:-/tmp}/vigil-trace.XXXXXX")
	(cd "$work" && java -XX:+UseParallelGC -Xss16m -DTLA-Library="$VERIFY_DIR/governor:$DIR" -cp "$JAR" tlc2.TLC \
		-workers "${TLC_WORKERS:-auto}" -cleanup -noGenerateSpecTE -nowarning -metadir "$meta" \
		-config GovernorTraceBatch.cfg GovernorTraceBatch.tla) >"$work/tlc.out" 2>&1
	rm -rf -- "${meta:?}"
	tlc=ok
	if ! grep -q "Model checking completed. No error has been found." "$work/tlc.out"; then
		tlc="$(verdict "$work/tlc.out")  (see ${work#"$VERIFY_DIR"/}/tlc.out)"
	fi
	acc=0; rej=0; first=""
	local i=0
	for f in "$@"; do
		i=$((i + 1))
		if [ -f "$work/res/accepted-$i.json" ]; then acc=$((acc + 1)); continue; fi
		rej=$((rej + 1))
		[ -n "$first" ] && continue
		local r; r=$(ls "$work/res/rejected-$i-"*.json 2>/dev/null | head -1)
		first=$(node -e '
			const fs = require("fs");
			const [file, rfile] = process.argv.slice(1);
			if (!rfile) { console.log(`  ${file}: no initial state of the model matches line 1 (the header: policy not in MCPolicies?)`); process.exit(0); }
			const r = JSON.parse(fs.readFileSync(rfile, "utf8"));
			const lines = fs.readFileSync(file, "utf8").trim().split("\n");
			const code = JSON.parse(lines[r.line - 1]);
			console.log(`  ${file}`);
			console.log(`  first unmatched step: line ${r.line} of ${lines.length}: ${r.action} ${r.args} at ${code.at} (slot ${code.state.now})`);
			console.log(`  ${r.why}`);
			if (r.diff) console.log(`  ${r.diff}`);
			console.log(`  code sent: [${code.sent.join(", ")}]`);
		' "$f" "$r")
	done
}

report_mutant() { # name kind description
	if [ "$tlc" != ok ] && [ "$rej" = 0 ]; then line FAIL "mutant/$1" "TLC: $tlc"; failed=1; return; fi
	if [ "$rej" -gt 0 ]; then
		line PASS "mutant/$1" "rejected, as expected: $rej/$((acc + rej)) traces ($2: $3)"
		printf "%s\n" "$first" | head -5 | sed 's/^/        /'
	else
		line FAIL "mutant/$1" "expected a rejected trace, all $acc accepted ($2: $3)"; failed=1
	fi
}

if [ ${#replay[@]} -gt 0 ]; then
	t0=$(date +%s); validate replay "${replay[@]}"; t=$(( $(date +%s) - t0 ))
	if [ "$rej" = 0 ] && [ "$tlc" = ok ]; then line PASS replay "$acc/${#replay[@]} traces accepted, ${t}s"
	else line FAIL replay "$acc/${#replay[@]} accepted; TLC: $tlc"; printf '%s\n' "$first"; failed=1; fi
	exit $failed
fi

# 1. The real code.
mkdir -p "$OUT"
t0=$(date +%s)
rm -rf -- "${OUT:?}/code/traces"
rec=$(node --experimental-strip-types "$DIR/record.ts" --out "$OUT/code/traces" --count "$count" --seed "$seed") || {
	line FAIL "trace/code" "record.ts failed: $rec"; exit 1; }
# Batches of at most 100 traces per TLC run (N, the most notices in a batch, sizes every state).
all=("$OUT"/code/traces/trace-*.ndjson); tacc=0; trej=0; tfirst=""; ttlc=ok; b=0
for ((k = 0; k < ${#all[@]}; k += 100)); do
	b=$((b + 1)); validate "code/batch-$b" "${all[@]:k:100}"
	tacc=$((tacc + acc)); trej=$((trej + rej))
	[ -z "$tfirst" ] && tfirst=$first
	[ "$ttlc" = ok ] && ttlc=$tlc
done
acc=$tacc; rej=$trej; first=$tfirst; tlc=$ttlc
t=$(( $(date +%s) - t0 ))
lines=$(cat "$OUT"/code/traces/trace-*.ndjson | wc -l)
pairs=$(sed -n 's/.*; \([0-9]*\) distinct.*/\1/p' <<<"$rec")
if [ "$tlc" = ok ] && [ "$rej" = 0 ]; then
	line PASS "trace/code" "$acc/$count traces accepted ($lines lines, seeds $seed..$((seed + count - 1)), $pairs (call, status change) pairs), ${t}s"
else
	failed=1
	[ "$rej" -gt 0 ] && line FAIL "trace/code" "$rej/$count traces REJECTED: the code did something the model does not allow (or the mapping is wrong)"
	[ "$tlc" != ok ] && line FAIL "trace/code" "TLC: $tlc"
	[ -n "$first" ] && printf '%s\n' "$first"
	echo "         Replay one: bash verification/governor/trace/check.sh --replay <trace file>; then read the verify skill, 'Trace validation'."
fi

# 2. The mutants. Each must have at least one of its traces rejected.
# mutant NAME code DESCRIPTION OLD NEW : patch a copy of src/core/governor.ts (OLD must occur in it
#                                        exactly once, copied exactly) and record with it;
# mutant NAME recorder DESCRIPTION FLAG : record with the real code and a broken recorder (record.ts FLAG).
mutant() {
	local name=$1 kind=$2 desc=$3 old=$4 new=${5:-} mdir="$OUT/mutant-$1" flags=()
	rm -rf -- "${mdir:?}/traces"; mkdir -p "$mdir/src"
	if [ "$kind" = code ]; then
		cp "$ROOT/src/core/governor.ts" "$ROOT/src/core/time.ts" "$mdir/src/"
		if ! node -e '
			const fs = require("fs"); const [f, a, b] = process.argv.slice(1);
			const s = fs.readFileSync(f, "utf8");
			if (s.split(a).length !== 2) process.exit(1);
			fs.writeFileSync(f, s.replace(a, () => b));' "$mdir/src/governor.ts" "$old" "$new"; then
			line FAIL "mutant/$name" "its old text is no longer in src/core/governor.ts exactly once: update it in check.sh"
			failed=1; return
		fi
		flags=(--governor "$mdir/src/governor.ts")
	else
		flags=("$old")
	fi
	node --experimental-strip-types "$DIR/record.ts" --out "$mdir/traces" --count "$mcount" --seed "$seed" "${flags[@]}" >"$mdir/record.out" 2>&1 || {
		line FAIL "mutant/$name" "record.ts failed (see ${mdir#"$VERIFY_DIR"/}/record.out)"; failed=1; return; }
	validate "mutant-$name" "$mdir"/traces/trace-*.ndjson
	report_mutant "$name" "$kind" "$desc"
}

if [ $mutants = 1 ]; then
	mutant no-gap code "offer() skips the minGapMinutes spacing check" \
		'const spaced = now - last >= policy.minGapMinutes * MINUTE;' \
		'const spaced = true;'
	mutant window-boundary code "within24h() also counts an interrupt exactly 24 h old (>= for >)" \
		'return times.filter((t) => t > now - DAY).length;' \
		'return times.filter((t) => t >= now - DAY).length;'
	mutant release-keeps-muted code "release() puts a claimed notice back although its topic was muted meanwhile (reverts 4d5f2c7)" \
		'const muted = (state.mutes[n.topic] ?? 0) > now;' \
		'const muted = false;'
	mutant digest-shows-stale code "takeForReply() flushes without expiring stale notices first (reverts 99a81e7)" \
		'const fresh = state.notices.map((n) => (isWaiting(n) && n.expiresAt <= now ? { ...n, status: "expired" as const, resolvedAt: now } : n));' \
		'const fresh = state.notices;'
	mutant prune-claimed code "tick() prunes a claimed notice older than HISTORY_MS mid-turn (reverts 4d5f2c7)" \
		'notices = notices.filter((n) => isWaiting(n) || n.status === "claimed" || n.createdAt > now - HISTORY_MS);' \
		'notices = notices.filter((n) => isWaiting(n) || n.createdAt > now - HISTORY_MS);'
	mutant unlogged-mute recorder "the recorder applies mute() but does not log the call (an instrumentation gap)" \
		--drop-mute-line
fi

echo
if [ $failed = 0 ]; then echo "governor-trace: PASS (${SECONDS}s)"; else echo "governor-trace: FAIL (${SECONDS}s)"; fi
exit $failed
