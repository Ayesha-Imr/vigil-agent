#!/usr/bin/env bash
# Trace validation of the outbox: record random runs of the real src/core/outbox.ts on a real
# in-memory Db (record.ts) and check with TLC that each is a behavior of
# verification/outbox/Outbox.tla (OutboxTrace.tla). Then show the check can fail: every mutant (a
# broken copy of outbox.ts, or a broken recorder) must have at least one trace rejected.
#
#   bash verification/outbox/trace/check.sh                   # 100 traces + 8 mutants, about 40 s on 4 cores
#   bash verification/outbox/trace/check.sh --count 400 --seed 1000
#   bash verification/outbox/trace/check.sh --no-mutants
#   bash verification/outbox/trace/check.sh --replay FILE.ndjson ...   # validate given trace files (one scenario)
#
# Lines: PASS / FAIL per check, then "outbox-trace: PASS" or "outbox-trace: FAIL". A rejected trace
# prints its first unmatched line, the step and what differs between model and code. Traces, TLC
# output and verdict files stay in verification/out/outbox-trace/. Exit 1 on any FAIL.
set -u
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$DIR/../../lib.sh"
ROOT="$(cd "$VERIFY_DIR/.." && pwd)"
command -v java >/dev/null || { echo "FAIL java not found (Java 11 or later is needed)"; exit 2; }
command -v node >/dev/null || { echo "FAIL node not found (Node 22 is needed to run record.ts)"; exit 2; }
JAR=$(find_jar) || exit 2
OUT="$VERIFY_DIR/out/outbox-trace"
NODE=(node --no-warnings --experimental-strip-types)
count=100; seed=1; group=20; mcount=20; mutants=1; replay=()
while [ $# -gt 0 ]; do
	case $1 in
		--count) count=$2; shift ;;
		--seed) seed=$2; shift ;;
		--group-size) group=$2; shift ;;
		--mutant-count) mcount=$2; shift ;;
		--no-mutants) mutants=0 ;;
		--replay) shift; replay=("$@"); break ;;
		*) echo "unknown option $1"; exit 2 ;;
	esac
	shift
done
failed=0
line() { printf '%-8s %-34s %s\n' "$1" "$2" "$3"; }

# validate NAME FILE... : one TLC run over a batch of traces of one scenario. Sets $acc, $rej
# (counts), $first (the report of the first rejected trace) and $tlc ("ok", or what went wrong).
validate() {
	local name=$1; shift
	local work="$OUT/$name/tlc"
	mkdir -p "$work/res"
	rm -f -- "${work:?}"/res/*.json
	local files="" f
	for f in "$@"; do files="${files:+$files, }\"$(realpath "$f")\""; done
	printf -- '---- MODULE OutboxTraceBatch ----\n\\* Generated by check.sh: the traces of one batch.\nEXTENDS OutboxTrace\nBatchFiles == <<%s>>\nBatchResultDir == "%s"\n====\n' \
		"$files" "$work/res" >"$work/OutboxTraceBatch.tla"
	cp "$DIR/OutboxTrace.cfg" "$work/OutboxTraceBatch.cfg"
	local meta; meta=$(mktemp -d "${TMPDIR:-/tmp}/vigil-trace.XXXXXX")
	(cd "$work" && java -XX:+UseParallelGC -Xss16m -DTLA-Library="$VERIFY_DIR/outbox:$DIR" -cp "$JAR" tlc2.TLC \
		-workers "${TLC_WORKERS:-auto}" -cleanup -noGenerateSpecTE -nowarning -metadir "$meta" \
		-config OutboxTraceBatch.cfg OutboxTraceBatch.tla) >"$work/tlc.out" 2>&1
	rm -rf -- "${meta:?}"
	tlc=ok
	if ! grep -q "Model checking completed. No error has been found." "$work/tlc.out"; then
		tlc="$(verdict "$work/tlc.out")  (see ${work#"$VERIFY_DIR"/}/tlc.out)"
	fi
	acc=0; rej=0; first=""
	local i=0
	for f in "$@"; do
		i=$((i + 1))
		if [ -f "$work/res/accepted-$i.json" ]; then acc=$((acc + 1)); continue; fi
		rej=$((rej + 1))
		[ -n "$first" ] && continue
		local r; r=$(ls "$work/res/rejected-$i-"*.json 2>/dev/null | head -1)
		first=$(node -e '
			const fs = require("fs");
			const [file, rfile] = process.argv.slice(1);
			if (!rfile) { console.log(`  ${file}: no initial state of the model matches line 1 (the header: another scenario than the batch, or a different initial state)`); process.exit(0); }
			const r = JSON.parse(fs.readFileSync(rfile, "utf8"));
			const lines = fs.readFileSync(file, "utf8").trim().split("\n");
			const code = JSON.parse(lines[r.line - 1]);
			console.log(`  ${file}`);
			console.log(`  first unmatched step: line ${r.line} of ${lines.length}: ${r.action} ${r.args}`);
			console.log(`  ${r.why}`);
			if (r.diff) console.log(`  ${r.diff}`);
			console.log(`  code sent: [${code.sent.map((d) => `row ${d.row} (${d.how})`).join(", ")}]`);
		' "$f" "$r")
	done
}

# validate_groups NAME DIR : one TLC run per scenario (file prefix gNN-) in DIR; sums the counts.
validate_groups() {
	local name=$1 dir=$2 g tacc=0 trej=0 tfirst="" ttlc=ok
	for g in $(ls "$dir"/g*-trace-*.ndjson | sed -E 's#.*/(g[0-9]+)-trace-.*#\1#' | sort -u); do
		validate "$name/$g" "$dir/$g"-trace-*.ndjson
		tacc=$((tacc + acc)); trej=$((trej + rej))
		[ -z "$tfirst" ] && tfirst=$first
		[ "$ttlc" = ok ] && ttlc=$tlc
	done
	acc=$tacc; rej=$trej; first=$tfirst; tlc=$ttlc
}

report_mutant() { # name kind description
	if [ "$tlc" != ok ] && [ "$rej" = 0 ]; then line FAIL "mutant/$1" "TLC: $tlc"; failed=1; return; fi
	if [ "$rej" -gt 0 ]; then
		line PASS "mutant/$1" "rejected, as expected: $rej/$((acc + rej)) traces ($2: $3)"
		printf "%s\n" "$first" | head -5 | sed 's/^/        /'
	else
		line FAIL "mutant/$1" "expected a rejected trace, all $acc accepted ($2: $3)"; failed=1
	fi
}

if [ ${#replay[@]} -gt 0 ]; then
	t0=$(date +%s); validate replay "${replay[@]}"; t=$(( $(date +%s) - t0 ))
	if [ "$rej" = 0 ] && [ "$tlc" = ok ]; then line PASS replay "$acc/${#replay[@]} traces accepted, ${t}s"
	else line FAIL replay "$acc/${#replay[@]} accepted; TLC: $tlc"; printf '%s\n' "$first"; failed=1; fi
	exit $failed
fi

# 1. The real code.
mkdir -p "$OUT"
t0=$(date +%s)
rm -rf -- "${OUT:?}/code"
rec=$("${NODE[@]}" "$DIR/record.ts" --out "$OUT/code/traces" --count "$count" --seed "$seed" --group-size "$group") || {
	line FAIL "trace/code" "record.ts failed: $rec"; exit 1; }
validate_groups code "$OUT/code/traces"
t=$(( $(date +%s) - t0 ))
lines=$(cat "$OUT"/code/traces/g*-trace-*.ndjson | wc -l)
groups=$(sed -n 's/.*, \([0-9]*\) scenarios).*/\1/p' <<<"$rec")
if [ "$tlc" = ok ] && [ "$rej" = 0 ]; then
	line PASS "trace/code" "$acc/$count traces accepted ($lines lines, seeds $seed..$((seed + count - 1)), $groups scenarios), ${t}s"
else
	failed=1
	[ "$rej" -gt 0 ] && line FAIL "trace/code" "$rej/$count traces REJECTED: the code did something the model does not allow (or the mapping is wrong)"
	[ "$tlc" != ok ] && line FAIL "trace/code" "TLC: $tlc"
	[ -n "$first" ] && printf '%s\n' "$first"
	echo "         Replay one: bash verification/outbox/trace/check.sh --replay <trace file>; then read the verify-outbox skill, 'Trace validation'."
fi

# 2. The mutants. Each must have at least one of its traces rejected.
# mutant NAME code DESCRIPTION OLD NEW : patch a copy of src/core/outbox.ts (OLD must occur in it
#                                        exactly once, copied exactly) and record with it;
# mutant NAME recorder DESCRIPTION FLAG : record with the real code and a broken recorder (record.ts FLAG).
mutant() {
	local name=$1 kind=$2 desc=$3 old=$4 new=${5:-} mdir="$OUT/mutant-$1" flags=()
	rm -rf -- "${mdir:?}"; mkdir -p "$mdir/src"
	if [ "$kind" = code ]; then
		# The copy imports the real modules (one PermanentSendError class for the channel and the copy).
		if ! node -e '
			const fs = require("fs"); const [src, f, root, a, b] = process.argv.slice(1);
			let s = fs.readFileSync(src, "utf8").replaceAll("from \"../", `from "${root}/src/`).replaceAll("from \"./", `from "${root}/src/core/`);
			if (s.split(a).length !== 2) process.exit(1);
			fs.writeFileSync(f, s.replace(a, () => b));' "$ROOT/src/core/outbox.ts" "$mdir/src/outbox.ts" "$ROOT" "$old" "$new"; then
			line FAIL "mutant/$name" "its old text is no longer in src/core/outbox.ts exactly once: update it in check.sh"
			failed=1; return
		fi
		flags=(--outbox "$mdir/src/outbox.ts")
	else
		flags=("$old")
	fi
	"${NODE[@]}" "$DIR/record.ts" --out "$mdir/traces" --count "$mcount" --seed "$seed" --group-size "$mcount" "${flags[@]}" >"$mdir/record.out" 2>&1 || {
		line FAIL "mutant/$name" "record.ts failed (see ${mdir#"$VERIFY_DIR"/}/record.out)"; failed=1; return; }
	validate_groups "mutant-$name" "$mdir/traces"
	report_mutant "$name" "$kind" "$desc"
}

if [ $mutants = 1 ]; then
	mutant heldback-due-only code "heldBack() counts only earlier rows that are due (Outbox.tla MutHeldBackDueOnly)" \
		'AND attempts < ?`,' \
		'AND attempts < ? AND next_attempt_at <= ${this.clock.now()}`,'
	mutant no-running-guard code "deliverDue() without the running guard: overlapping passes (MutNoRunningGuard)" \
		'if (this.running || !this.mayDeliver()) return 0;' \
		'if (!this.mayDeliver()) return 0;'
	mutant refs-outside-tx code "the sent UPDATE and the message_refs INSERT outside db.tx (MutRefOutsideTx)" \
		'this.db.tx(() => {' \
		'((f) => f())(() => {'
	mutant no-split-key code "enqueue() gives the parts of a long message no order key (MutNoSplitKey)" \
		'const orderKey = item.orderKey ?? (parts.length > 1 ? `split:${now}:${Math.random()}` : null);' \
		'const orderKey = item.orderKey ?? null;'
	mutant pending-only code "deliverDue() selects only pending rows, never failing ones (MutPendingOnly)" \
		"status IN ('pending', 'failing') AND next_attempt_at <= ? ORDER BY id" \
		"status IN ('pending') AND next_attempt_at <= ? ORDER BY id"
	mutant no-send-timeout code "channel.send awaited without withTimeout (MutNoSendTimeout)" \
		'await withTimeout(SEND_TIMEOUT_MS, channel.send({' \
		'await (channel.send({'
	mutant failing-one-late code "a row turns failing after BLOCKING_ATTEMPTS + 1 errors (> for >=; no model mutant)" \
		'attempts >= BLOCKING_ATTEMPTS ? "failing" : "pending"' \
		'attempts > BLOCKING_ATTEMPTS ? "failing" : "pending"'
	mutant unlogged-enqueue recorder "the recorder runs the second enqueue() but does not log it (an instrumentation gap)" \
		--drop-enqueue-line
fi

echo
if [ $failed = 0 ]; then echo "outbox-trace: PASS (${SECONDS}s)"; else echo "outbox-trace: FAIL (${SECONDS}s)"; fi
exit $failed
